// Self-check, not bundled: `node src/lib/format.check.ts` (Node ≥ 23 strips the types); `npm run check` runs every *.check.ts with node --test.
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { fmtDate, fmtFx, fmtMoney, fmtPct, fmtTick, fxShown, parseAmount, parseDay, parseFx, setDateLang } from "./format.ts"

// The same cases internal/ledger/import.go's parseAmount is tested against (TestParseAmount).
const amounts = JSON.parse(readFileSync(new URL("../../../internal/ledger/testdata/amounts.json", import.meta.url), "utf8"))
for (const [input, want] of Object.entries(amounts.valid)) assert.equal(parseAmount(input), want, input)
for (const input of amounts.invalid) assert.equal(parseAmount(input), NaN, input)

assert.deepStrictEqual(fmtDate("2026-10-03"), "2026.10.03")
assert.deepStrictEqual(fmtTick("2026-10-03", false), "2026.10")
assert.deepStrictEqual(fmtTick("2026-10-03", true), "10/03")
assert.deepStrictEqual(parseFx("0.0000385"), 0.0000385)
assert.deepStrictEqual(parseFx("31.88840576"), 31.88840576)
assert.deepStrictEqual(parseFx("1,234.5"), 1234.5)
assert.deepStrictEqual(parseFx(""), NaN)
assert.deepStrictEqual(parseFx("-1"), NaN)
assert.deepStrictEqual(fmtFx(0.00074458), "0.00074458")
assert.deepStrictEqual(fmtFx(0.0000559), "0.0000559")
assert.deepStrictEqual(fmtFx(31.88840576), "31.8884")
assert.deepStrictEqual(fmtFx(16234.5), "16,234.5")
setDateLang("en")
assert.deepStrictEqual(fmtTick("2026-10-03", false), "Oct 2026")
assert.deepStrictEqual(fmtTick("2026-10-03", true), "Oct 3")
assert.deepStrictEqual(fmtDate("2026-10-03"), "Oct 3, 2026")
assert.deepStrictEqual(fmtDate("2026-10"), "Oct 2026")
setDateLang("zh")
assert.deepStrictEqual(fmtMoney(12345678, "wan"), "1,234.6萬")
assert.deepStrictEqual(fmtMoney(123456789, "wan"), "1.23億")
assert.deepStrictEqual(fmtMoney(9999, "wan"), "9,999")
assert.deepStrictEqual(fmtMoney(-25000, "wan"), "−2.5萬")
assert.deepStrictEqual(fmtMoney(12345678, "k"), "12.35M")
assert.deepStrictEqual(fmtMoney(1500, "k", "en", { signed: true }), "+1.5K")
assert.deepStrictEqual(fmtMoney(12345678.4, "full"), "12,345,678")
assert.deepStrictEqual(fmtMoney(-0.2, "full"), "0")
assert.deepStrictEqual(fmtPct(0.0234), "2.3%")
assert.deepStrictEqual(fmtPct(-0.05, 0, true), "−5%")

// round before picking the unit (round 3: 99,999,999 printed "10,000萬")
assert.equal(fmtMoney(99_999_999, "wan"), "1億")
assert.equal(fmtMoney(999_999, "k"), "1M")
assert.equal(fmtMoney(9_999.6, "wan"), "1萬")
assert.equal(fmtMoney(-999_999_999, "k", "en"), "−1B")
// typed dates are strict: no rolling 02-31 into March, no stray text
assert.equal(parseDay("2026-10-03"), "2026-10-03")
assert.equal(parseDay("2026.1.5"), "2026-01-05")
assert.equal(parseDay("2026/10/3"), "2026-10-03")
assert.equal(parseDay("Oct 3, 2026"), "2026-10-03")
assert.equal(parseDay("october 3 2026"), "2026-10-03")
assert.equal(parseDay("2026-02-31"), null)
assert.equal(parseDay("2024-02-29"), "2024-02-29")
assert.equal(parseDay("foo 5"), null)
assert.equal(parseDay("0005-01-01"), null)
// rates: 6 significant digits while not focused, the full typed text while focused (a VND row on a USD ledger)
assert.equal(fxShown("31.93097389", false), "31.931")
assert.equal(fxShown("31.93097389", true), "31.93097389")
assert.equal(fxShown("abc", false), "abc")
assert.equal(parseFx(String(0.0000385)), 0.0000385)
assert.equal(fxShown(String(0.0000385), false), "0.0000385")
