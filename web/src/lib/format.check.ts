// Self-check, not bundled: `node src/lib/format.check.ts` (Node ≥ 23 strips the types).
import { fmtDate, fmtFx, fmtMoney, fmtPct, fmtTick, parseAmount, parseFx, setDateLang } from "./format.ts"

const eq = (got: unknown, want: unknown) => {
  if (!Object.is(got, want)) throw new Error(`got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`)
}
eq(parseAmount("1,234,567"), 1234567)
eq(parseAmount("12.5萬"), 125000)
eq(parseAmount("3k"), 3000)
eq(parseAmount("1.2億"), 120000000)
eq(parseAmount("−500"), -500)
eq(parseAmount("１２３"), 123)
eq(parseAmount(" 0 "), 0)
eq(parseAmount("abc"), NaN)
eq(parseAmount(""), NaN)
eq(parseAmount("1.234,56"), NaN) // European decimal comma: ambiguous, rejected
eq(parseAmount("12,34"), NaN)
eq(parseAmount("1,234.5萬"), 12345000)
eq(fmtDate("2026-10-03"), "2026.10.03")
eq(fmtTick("2026-10-03", false), "2026.10")
eq(fmtTick("2026-10-03", true), "10/03")
eq(parseFx("0.0000385"), 0.0000385)
eq(parseFx("31.88840576"), 31.88840576)
eq(parseFx("1,234.5"), 1234.5)
eq(parseFx(""), NaN)
eq(parseFx("-1"), NaN)
eq(fmtFx(0.00074458), "0.00074458")
eq(fmtFx(0.0000559), "0.0000559")
eq(fmtFx(31.88840576), "31.8884")
eq(fmtFx(16234.5), "16,234.5")
setDateLang("en")
eq(fmtTick("2026-10-03", false), "Oct 2026")
eq(fmtTick("2026-10-03", true), "Oct 3")
eq(fmtDate("2026-10-03"), "Oct 3, 2026")
eq(fmtDate("2026-10"), "Oct 2026")
setDateLang("zh")
eq(fmtMoney(12345678, "wan"), "1,234.6萬")
eq(fmtMoney(123456789, "wan"), "1.23億")
eq(fmtMoney(9999, "wan"), "9,999")
eq(fmtMoney(-25000, "wan"), "−2.5萬")
eq(fmtMoney(12345678, "k"), "12.35M")
eq(fmtMoney(1500, "k", "en", { signed: true }), "+1.5K")
eq(fmtMoney(12345678.4, "full"), "12,345,678")
eq(fmtMoney(-0.2, "full"), "0")
eq(fmtPct(0.0234), "2.3%")
eq(fmtPct(-0.05, 0, true), "−5%")
console.log("format ok")
